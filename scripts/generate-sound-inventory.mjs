import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const publicRoot = path.join(projectRoot, "public");
const outputPath = path.join(projectRoot, "src", "generated", "sound-inventory.ts");
const audioExtensions = new Set([".mp3", ".wav", ".ogg", ".m4a", ".aac"]);
const roots = ["sound", "sounds"];

async function collectFiles(directory, result) {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") return;
    throw error;
  }

  for (const entry of entries) {
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      await collectFiles(absolutePath, result);
      continue;
    }

    if (!entry.isFile() || !audioExtensions.has(path.extname(entry.name).toLowerCase())) {
      continue;
    }

    const relativePath = path.relative(publicRoot, absolutePath).split(path.sep).join("/");
    result.add(`/${relativePath}`);
  }
}

const files = new Set();
for (const root of roots) {
  await collectFiles(path.join(publicRoot, root), files);
}

const paths = [...files].sort((left, right) => left.localeCompare(right));
const source = `// Generated by scripts/generate-sound-inventory.mjs.\n// Do not edit manually.\nexport const SOUND_FILE_PATHS = ${JSON.stringify(paths, null, 2)} as const;\n`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");
console.log(`Generated ${paths.length} sound paths in ${path.relative(projectRoot, outputPath)}`);
