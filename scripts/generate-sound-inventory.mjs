import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SOUND_BY_ID } from "../src/shared/sound-inventory-rules.mjs";
import { scanAndReconcileManifest } from "./sound-inventory-store.mjs";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(projectRoot, "src", "generated", "sound-inventory.ts");
const result = await scanAndReconcileManifest(projectRoot, SOUND_BY_ID);
const paths = [...new Set(result.records.filter((record) => record.available).map((record) => record.path))]
  .sort((left, right) => left.localeCompare(right));
const source = `// Generated by scripts/generate-sound-inventory.mjs.\n// Do not edit manually.\nexport const SOUND_FILE_PATHS = ${JSON.stringify(paths, null, 2)} as const;\n`;

await mkdir(path.dirname(outputPath), { recursive: true });
let existingSource = "";
try {
  existingSource = await readFile(outputPath, "utf8");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}
if (existingSource.replace(/\r\n/g, "\n") !== source) {
  await writeFile(outputPath, source, "utf8");
}

console.log(
  `Sound inventory: ${result.found} found, ${result.added.length} new, ${result.existing.length} already registered, ${result.absent.length} absent, ${result.omitted} omitted.`,
);
